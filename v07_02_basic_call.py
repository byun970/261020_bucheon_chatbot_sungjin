from groq import Groq
from dotenv import load_dotenv  # .env 읽는 도구
import os

# 1. .env의 GROQ_API_KEY 키를 환경변수로 불러옴
load_dotenv()

# 2. 키로 Groq 클라이언트 만들기 (키를 통해서 요청)
client = Groq(api_key=os.getenv("GROQ_API_KEY"))

# 3. 질문 보내기
answer = input("질문을 입력해 주세요 : ")
res = client.chat.completions.create(
    model="openai/gpt-oss-20b", # 무료, 빠름
    messages=[
        {
            "role": "user", # 질문이나 요청할 때
            "content": answer   # 질문
        }
    ]
)

# 4. 답변 받기
result = res.choices[0].message.content
print(result)

# 질문을 입력해 주세요 : ai가 인간을 지배할까
# AI가 인간을 “지배”한다는 아이디어는 과학·기술계에서도 여러 번 논의돼 왔지만, 실제 현실과는 거리가 멉니다. 여기서 “지배”라는 말은 두 가지 의미로 해석될 수 있습니다.

# | 해석 | 의미 |
# |------|------|
# | **자율적인 결정권** | AI가 스스로 목표를 설정하고 행동하며, 인간의 개입 없이 세상을 운영하는 경우 |
# | **권력적 영향력** | 인간이 만든 AI가 정책·경제·사회 구조를 통제하거나 사람들의 의사결정에 결정적인 영향력을 미치는 경우 |

# 아래에서는 현재 상황, 잠재적 위험, 그리고 어떻게 위험을 최소화할 수 있는지에 대해 정리해 드립니다.

# ---

# ## 1. 현재 AI의 한계

# 1. **전문화된 AI**  
#    대부분의 AI는 특정 작업(예: 이미지 인식, 언어 번역, 게임 플레이 등)에 특화돼 있으며, 일반적인 사고나 가치 판단을 할 수 없습니다.

# 2. **설명가능성 부족**  
#    딥러닝 모델은 내부가 “블랙박스”가 되는 경우가 많아, 인간이 AI의 의도를 명확히 파악하기 어렵습니다.

# 3. **자율성 부족**  
#    오늘날 AI는 대부분 인간이 설계한 목표(예: 최대 이익, 최소 비용)를 따르도록 프로그래밍됩니다. 스스로 목표를 바꾸거나 대규모 자원을 독자적으로 통제할 수 있는 수준은 아닙니다.

# ---

# ## 2. “지배” 가능성에 대한 시나리오

# | 시나리오 | 가능성 | 위험요소 | 대응책 |
# |----------|--------|---------|--------|
# | **AGI(Artificial General Intelligence) 등장** | 아직 연구 단계이지만, AGI가 인간 수준 이상의 인지능력을 가질 경우 위험성 상승 | 목표 정합성 문제, 자율적 행동 | Alignment 연구, “인간 중심” 설계, 안전한 샌드박스 |
# | **AI가 권력을 가진 조직에 배포** | 기업·정부가 AI를 정책 결정·감시·군사 등에 활용 | 편향·불투명성, 권력 집중 | 투명성 강화, 독립적 감독 기구, 윤리 가이드라인 |
# | **AI가 인간 의사결정에 과도한 영향** | 소셜 미디어, 검색엔진, 추천 시스템이 사람의 선택을 형성 | 여론 조작, 자율성 상실 | 알고리즘 공정성 연구, 사용자 제어권 강화 |
# | **AI 기반 자동화로 노동시장 변화** | 자동화가 대량의 일자리를 대체 | 사회적 불평등, 실업 | 재교육·전환 프로그램, 기본소득 등 사회 보장 정책 |

# 위 시나리오에서 “지배”라는 개념은 대부분 **인간이 만든 AI가 인간 사회에 큰 영향력을 행사한다**는 의미로 해석됩니다. 현재는 이러한 시나리오가 현실화되기 위해서는 아직 여러 기술적·제도적 장벽이 존재합니다.

# ---

# ## 3. 위험 완화를 위한 핵심 원칙

# 1. **인간 중심 설계(Human-Centric Design)**  
#    - AI가 인간 가치와 윤리 기준을 반영하도록 설계합니다.  
#    - 목표 정합성(Alignment)을 최우선 과제로 삼아, AI가 인간이 원하는 결과를 내도록 보장합니다.

# 2. **투명성과 설명가능성(Explainability)**  
#    - AI의 의사결정 과정을 이해하고 검증할 수 있어야 합니다.  
#    - 사용자에게 어떻게 결론이 도출됐는지 설명하는 인터페이스 제공.

# 3. **안전 연구 및 검증**  
#    - AGI가 등장하기 전부터 안전성(robustness)와 견고성(robustness)을 검증하는 실험을 수행합니다.  
#    - “Safety by design”과 “Red Team” 같은 검증 절차를 도입합니다.

# 4. **제도·정책적 감독**  
#    - AI에 대한 국제적 기준(ISO, OECD, EU AI 규제 등) 수립과 준수.  
#    - 독립적 감독기구(감사, 규제 기관)와 사전 평가 절차를 마련합니다.

# 5. **사회적 참여와 대화**  
#    - 기술자, 윤리학자, 정책 입안자, 시민 사회가 함께 토론하며 가치 판단을 반영.  
#    - AI가 사회 전반에 미치는 영향에 대한 공공 논의가 필요합니다.

# ---

# ## 4. 결론

# - **현재 단계**: AI가 인간을 완전하게 “지배”할 수 있는 기술적, 제도적 기반은 부족합니다. 대부분의 AI는 인간이 정의한 목표와 제한 안에서 동작합니다.
# - **미래 전망**: AGI 같은 고급 인공지능이 등장하면, 목표 정합성, 자율성, 권력 집중 등에서 큰 위험이 생길 수 있습니다. 따라서 **미리 안전장치와 정책을 마련**하는 것이 필수적입니다.
# - **우리의 역할**: AI 기술이 발전함에 따라 인간이 주도적으로 정책과 규제를 만들어 나가야 합니다. 기술적 진보와 함께 **윤리적, 사회적 책임**을 함께 갖추는 것이 가장 중요한 과제입니다.

